function rankDomains(query) {
  const q = query.toLowerCase();
  return KNOWLEDGE.map(d => ({...d, score:d.topics.reduce((n,t)=>n+(q.includes(t)?(t.length>5?3:1):0),0)}))
    .filter(d=>d.score>0).sort((a,b)=>b.score-a.score).slice(0,5)
    .map(({id,name,scope})=>({id,name,scope}));
}

